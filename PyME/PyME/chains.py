class Chain(object):
    def __init__(self, power, app_factor, ratio, drive_speed):
        self.power = power
        self.app_factor = app_factor
        self.ratio = ratio
        self. drive_speed = drive_speed
        self.equivalent_power = self.power * self.app_factor
        pass

    def step1_calc_diagram_power(self, z1, num_of_trolleys: int):
        self.z1 = z1
        self.num_of_trolleys = num_of_trolleys
        index = np.where(_TROLLEY_TEETH_ >= self.z1 * self.ratio)
        self.z2 = _TROLLEY_TEETH_[index][0]
        self.ratio = self.z2 / self.z1
        self.equivalent_torque = self.power / self.drive_speed * 9550 * self.app_factor
        f1 = (19 / self.z1)**1.08
        f4 = 0.9 ** (self.num_of_trolleys - 2)
        self.diagram_power = self.equivalent_power * f1 / f4 / 0.98
        return self.diagram_power

    def step_2_calc_shaft_distance(self, chain_type: str, prov_shaft_distance):
        self.chain_type = chain_type
        self.chain_params = _CHAIN_TYPE_.get(chain_type)
        self.partition = self.chain_params[0]
        t1 = 2 * prov_shaft_distance / self.partition
        t2 = (self.z1 + self.z2) / 2
        t3 = (self.z2 - self.z1 / (np.pi * 2))**2 * self.partition / prov_shaft_distance
        X0 =t1 + t2 + t3
        self.X = np.ceil(X0/2) * 2
        zm = (self.z1 + self.z2)/2
        t1 = self.X - zm
        t2 = 2 * ((self.z2 - self.z1) / np.pi)**2
        self.shaft_distance = self.partition / 4 * (t1 + np.sqrt(t1**2 - t2))
